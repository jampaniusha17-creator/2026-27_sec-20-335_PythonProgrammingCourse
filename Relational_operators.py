# Program to demonstrate relational operators

a = int(input("Enter first number: "))
b = int(input("Enter second number: "))

print("a =", a)
print("b =", b)

print("a > b  :", a > b)
print("a < b  :", a < b)
print("a >= b :", a >= b)
print("a <= b :", a <= b)
print("a == b :", a == b)
print("a != b :", a != b)