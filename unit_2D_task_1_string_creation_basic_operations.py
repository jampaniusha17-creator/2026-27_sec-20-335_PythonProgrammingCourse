# String Creation
str1 = "Hello"
str2 = "World"

print("String 1:", str1)
print("String 2:", str2)

# String Concatenation
result = str1 + " " + str2
print("Concatenation:", result)

# String Repetition
repeat = str1 * 3
print("Repetition:", repeat)

# String Slicing
print("First 3 characters:", result[0:3])
print("Characters from index 3 to 7:", result[3:8])
print("Last 5 characters:", result[-5:])