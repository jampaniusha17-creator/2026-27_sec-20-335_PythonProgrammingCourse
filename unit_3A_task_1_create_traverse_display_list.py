# Create a list
my_list = [10, 20, 30, 40, 50]

# Display the list
print("List elements:", my_list)

# Traverse the list using for loop
print("Traversing the list:")
for element in my_list:
    print(element)

# Display elements using index
print("Displaying elements using index:")
for i in range(len(my_list)):
    print("Element at index", i, "=", my_list[i])